"""Generate QMK-ready C snippets (matrix pins, LAYOUT, IS31FL3733 LED table, g_led_config)
straight from the stock firmware tables.  Usage: python gen_qmk_tables.py > qmk_snippets_v1_12.c
"""
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
BASE = 0x08004000
img = (Path(__file__).resolve().parents[2] / "stock/firmware/HuntsmanMini_dev1_v1.12.00.bin").read_bytes()
rd = lambda a, n: img[a - BASE:a - BASE + n]

KN = {1: "GRV", 2: "1", 3: "2", 4: "3", 5: "4", 6: "5", 7: "6", 8: "7", 9: "8", 10: "9", 11: "0", 12: "MINS",
      13: "EQL", 15: "BSPC", 16: "TAB", 17: "Q", 18: "W", 19: "E", 20: "R", 21: "T", 22: "Y", 23: "U", 24: "I",
      25: "O", 26: "P", 27: "LBRC", 28: "RBRC", 29: "BSLS", 30: "CAPS", 31: "A", 32: "S", 33: "D", 34: "F", 35: "G",
      36: "H", 37: "J", 38: "K", 39: "L", 40: "SCLN", 41: "QUOT", 42: "NUHS", 43: "ENT", 44: "LSFT", 45: "NUBS",
      46: "Z", 47: "X", 48: "C", 49: "V", 50: "B", 51: "N", 52: "M", 53: "COMM", 54: "DOT", 55: "SLSH", 57: "RSFT",
      58: "LCTL", 59: "FN", 60: "LALT", 61: "SPC", 62: "RALT", 64: "RCTL", 110: "ESC", 127: "LGUI", 129: "APP"}
MODS = {"ESC", "TAB", "CAPS", "LSFT", "RSFT", "LCTL", "LGUI", "LALT", "RALT", "FN", "APP", "RCTL", "ENT", "BSPC"}

PORTS = {0x40020000: "A", 0x40020400: "B", 0x40020800: "C"}
rows = [PORTS[struct.unpack("<III", rd(0x080103C0 + 12 * i, 12))[0]] + str(struct.unpack("<III", rd(0x080103C0 + 12 * i, 12))[2]) for i in range(8)]
cols = [PORTS[struct.unpack("<III", rd(0x08010420 + 12 * i, 12))[0]] + str(struct.unpack("<III", rd(0x08010420 + 12 * i, 12))[2]) for i in range(8)]
km = rd(0x08010380, 64)
pos = {km[i]: (i // 8, i % 8) for i in range(64) if km[i]}

# physical positions from the LampArray tables (units of 10 um); ISO table covers ISO-only keys
phys = {}
for tab, n in ((0x08011B65, 0x3E), (0x080119BA, 0x3D)):   # ANSI last so it wins for shared keys
    for i in range(n):
        lid, x, y, usage, k = struct.unpack("<BHHBB", rd(tab + 7 * i, 7))
        phys[k] = (x, y)

leds = []
for r in range(5):
    for c in range(15):
        e = rd(0x08010657 + 7 * (r * 15 + c), 7)
        if e[0]:
            leds.append(e)


def swcs(v):
    return f"SW{(v >> 4) + 1}_CS{(v & 15) + 1}"


print("/* Generated by re/firmware/gen_qmk_tables.py from stock v1.12.00 - verify on hardware */")
print(f"#define MATRIX_ROWS 8\n#define MATRIX_COLS 8")
print("#define MATRIX_ROW_PINS { " + ", ".join(rows) + " }   /* drive, active LOW */")
print("#define MATRIX_COL_PINS { " + ", ".join(cols) + " }   /* sense, LOW = pressed */\n")

print("/* matrix [row][col] -> key (stock key-number table @0x08010380) */")
for r in range(8):
    print("/* r%d %-4s */ " % (r, rows[r]) + " ".join(f"{KN.get(km[r*8+c], '---'):>5s}" for c in range(8)))

print("\n/* IS31FL3733 @0x50 (ADDR1=ADDR2=GND), order = stock 5x15 LED grid, {driver, R, G, B} */")
print("const is31fl3733_led_t PROGMEM g_is31fl3733_leds[IS31FL3733_LED_COUNT] = {")
for e in leds:
    print(f"    {{0, {swcs(e[4])}, {swcs(e[5])}, {swcs(e[6])}}}, /* {KN[e[0]]} */")
print("};  /* IS31FL3733_LED_COUNT = %d */\n" % len(leds))

xs = [phys[e[0]][0] for e in leds]
ys = [phys[e[0]][1] for e in leds]
x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
print("led_config_t g_led_config = { {")
grid = [["NO_LED"] * 8 for _ in range(8)]
for i, e in enumerate(leds):
    r, c = pos[e[0]]
    grid[r][c] = str(i)
for r in range(8):
    print("    { " + ", ".join(f"{v:>6s}" for v in grid[r]) + " },")
print("}, {")
pts = []
for e in leds:
    x, y = phys[e[0]]
    pts.append(f"{{{round((x - x0) * 224 / (x1 - x0)):3d},{round((y - y0) * 64 / (y1 - y0)):2d}}}")
for i in range(0, len(pts), 8):
    print("    " + ", ".join(pts[i:i + 8]) + ",")
print("}, {")
fl = ["1" if KN[e[0]] in MODS else "4" for e in leds]
for i in range(0, len(fl), 16):
    print("    " + ", ".join(fl[i:i + 16]) + ",")
print("} };")
